print('\n=== 検証 ===')
import re
issues = []
for path in EXTENSIONS:
    with open(path, encoding='utf-8') as f:
        html = f.read()
    m = re.search(r'<meta name="description" content="(.*?)" */?>', html)
    if m:
        length = len(m.group(1))
        if length < 80 or length > 120:
            issues.append((path, length))
if issues:
    for p, l in issues:
        print(f'  範囲外: {p} ({l}文字)')
