def main():
    total_files = 0
    total_replacements = 0
    errors = []

    for path, pairs in REPLACEMENTS.items():
        with open(path, encoding='utf-8') as f:
            text = f.read()
        original = text
        file_changes = 0
        for old, new in pairs:
            count = text.count(old)
            if count == 0:
                errors.append(f'NOT FOUND in {path}: {old[:60]}...')
                continue
            if count > 1:
                errors.append(f'MULTIPLE({count}) in {path}: {old[:60]}...')
            text = text.replace(old, new)
            file_changes += 1
            total_replacements += 1

        if text != original:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
            total_files += 1
            print(f'  Updated: {path} ({file_changes} replacements)')

    print(f'\n合計: {total_files}ファイル更新, {total_replacements}件置換')
    if errors:
        print(f'\n=== 警告 ({len(errors)}件) ===')
        for e in errors:
            print(f'  {e}')
    else:
        print('\n警告なし：全置換が想定通り1回ずつ適用されました')


if __name__ == '__main__':
    main()
